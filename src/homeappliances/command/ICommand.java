package homeappliances.command;

/**
 * Інтерфейс для реалізації Шаблону Команда.
 * Кожна дія в меню буде окремим класом, що реалізує цей інтерфейс.
 */
public interface ICommand {

    /**
     * Повертає назву команди для відображення в меню.
     * @return Назва команди.
     */
    String getName();

    /**
     * Виконує основну логіку команди.
     */
    void execute();
}
